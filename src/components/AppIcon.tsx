function normalizeEmoji(value: string) {
  return value.replace(/\uFE0F/g, '').trim();
}

export function AppIcon({ name, ...props }: { name: string } & LucideProps) {
  const Icon = ICONS[name as IconName] ?? Sparkles;
  return <Icon aria-hidden="true" {...props} />;
}

export function EmojiIcon({ emoji, ...props }: { emoji?: string | null } & LucideProps) {
  const raw = emoji?.trim() ?? '';
  if (raw && raw in ICONS) return <AppIcon name={raw} {...props} />;
  const key = normalizeEmoji(raw);
  const name = (key && EMOJI_ICONS[key]) || (raw && EMOJI_ICONS[raw]) || 'sparkles';
  return <AppIcon name={name} {...props} />;
}
